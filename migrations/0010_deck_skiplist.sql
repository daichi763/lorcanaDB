-- ============================================================================
-- 取り込めなかったデッキURLの記録
--
-- なぜ必要か:
--   デッキレシピの取り込みは「合計60枚」を条件にしている（デッキ構築の規定枚数）。
--   ところが出典サイト側のデータに誤りがあり、61〜63枚として掲載されている
--   ページが実在する（実測: 900066=63枚, 900084=62枚, 900112=61枚。
--   いずれも出典ページ自身が合計欄にその枚数を表示している）。
--
--   これらは meta_decks に入らないため「未取得」と判定され、収集を繰り返す
--   たびに毎回もう一度ダウンロードされていた。相手サーバに無駄な負荷をかけ、
--   1回あたりの取得枠も食いつぶすので、除外の事実を残して次回は飛ばす。
--
--   「取り込まない」という判断自体を記録に残す意味もある。件数が想定より
--   少ないときに、通信で落ちたのか出典データが規定外なのかを後から追える。
-- ============================================================================

CREATE TABLE IF NOT EXISTS meta_deck_skips (
  url          TEXT PRIMARY KEY,
  source_key   TEXT,
  -- 除外理由。'not_60' = 合計が60枚でない / 'no_table' = デッキ表が無い / 'http_error'
  reason       TEXT NOT NULL,
  -- 実際に数えた枚数（分かる場合）。出典側の誤りを説明できるように残す
  counted      INTEGER,
  -- 何回試したか。出典が修正されたら取り込めるようになるので、
  -- 完全に永久除外はせず再挑戦の判断材料として持つ
  attempts     INTEGER NOT NULL DEFAULT 1,
  first_seen   TEXT DEFAULT (datetime('now')),
  last_seen    TEXT DEFAULT (datetime('now'))
);
CREATE INDEX IF NOT EXISTS idx_meta_deck_skips_reason ON meta_deck_skips(reason, last_seen DESC);
